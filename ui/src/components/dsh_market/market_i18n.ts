export type Market_translate = (key: Market_message_key, values?: Record<string, string | number>) => string;
export function market_translate(locale: Market_locale): Market_translate {
  const messages = locale === 'zh' ? chinese : english;
  return (key, values) => messages[key].replace(/\{(\w+)\}/g, (match, name: string) => String(values?.[name] ?? match));
}
