export type Dsh_translate = (key: Dsh_message_key | string) => string;

export function use_dsh_i18n(): Dsh_translate {
  const { locale } = useCtx();
  const catalog: Record<string, string> = locale === 'zh' ? chinese : english;
  return (key) => catalog[key] ?? key;
}
